type MaybeStore = Pick<Storage, 'getItem' | 'setItem'> | null | undefined;

function read(store: MaybeStore, key: string) { try { return store?.getItem(key) ?? ''; } catch { return ''; } }
function write(store: MaybeStore, key: string, value: string) { try { store?.setItem(key, value); } catch { /* modo privado ou bloqueado: segue sem lembrar */ } }

/** As dicas já dadas neste navegador. `claim` diz se esta é a primeira vez e a marca como dada. Sem storage, vale para a aba. */
export class HintBook {
  private seen: Set<string>;
  constructor(private store: MaybeStore) {
    this.seen = new Set(read(store, HINTS_KEY).split(',').filter(Boolean));
  }
  claim(key: HintKey): boolean {
    if (this.seen.has(key)) return false;
    this.seen.add(key);
    write(this.store, HINTS_KEY, [...this.seen].join(','));
    return true;
  }
}

const isLang = (s: string): s is Lang => (LANGS as string[]).includes(s);
/** A língua lembrada pelo navegador; português quando não há nada (ou algo que não é língua) guardado. */
export function readLang(store: MaybeStore): Lang { const s = read(store, LANG_KEY); return isLang(s) ? s : DEFAULT_LANG; }
export function writeLang(store: MaybeStore, lang: Lang) { write(store, LANG_KEY, lang); }
